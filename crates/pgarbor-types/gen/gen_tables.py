def rs_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def b(s):
    return 'true' if s == 't' else 'false'


def ch(s):
    if not s:
        return "b' '"
    c = s[0]
    if c == "'":
        return "b'\\''"
    if c == '\\':
        return "b'\\\\'"
    return "b'" + c + "'"


def pg_array(s):
    """Parse a simple PG text array like {a,b,"c d"} into a list of strings."""
    if not s:
        return []
    assert s[0] == '{' and s[-1] == '}', s
    body = s[1:-1]
    out, cur, q, i = [], '', False, 0
    while i < len(body):
        c = body[i]
        if q:
            if c == '\\':
                i += 1
                cur += body[i]
            elif c == '"':
                q = False
            else:
                cur += c
        else:
            if c == '"':
                q = True
            elif c == ',':
                out.append(cur)
                cur = ''
            else:
                cur += c
        i += 1
    out.append(cur)
    return out


