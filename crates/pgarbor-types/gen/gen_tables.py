def classify(p):
    kind = p['prokind']
    if kind == 'a':
        return agg_module.get(p['oid'], 'Unsupported')
    if kind == 'w':
        return 'Window'
    src = p['prosrc']
    name = p['proname']
    arg_t = [tname.get(a, a) for a in p['proargtypes'].split()]
    if any(a in GEO for a in arg_t) or tname.get(p['prorettype']) in GEO:
        return 'Unsupported'
    if p['prolang'] == '14':
        if 'bytea' in arg_t and name == 'bit_length':
            return 'Bytea'
        # SQL-language builtins: implemented natively, matched by proc OID.
        if name in EXTERNAL_SQL_NAMES:
            return 'External'
        if name in SYSTEM_SQL_NAMES:
            return 'System'
        if name in ('lpad', 'rpad', 'bit_length', 'substring', 'textanycat', 'anytextcat'):
            return 'Text' if not name == 'substring' else 'Regex'
        if name in ('quote_literal', 'quote_nullable'):
            return 'TextFormat'
        if name in ('timestamptz', 'timedate_pl', 'timetzdate_pl', 'interval_pl_time', 'interval_pl_date',
                    'interval_pl_timetz', 'interval_pl_timestamp', 'interval_pl_timestamptz', 'integer_pl_date'):
            return 'Timestamp' if name in ('timestamptz', 'timedate_pl', 'timetzdate_pl', 'interval_pl_date',
                                           'interval_pl_timestamp', 'interval_pl_timestamptz') else (
                'Date' if name == 'integer_pl_date' else 'Time')
        if name in ('overlaps', 'date_part', 'age'):
            return 'DatetimeFuncs'
        if name in ('log10', 'round', 'trunc', 'log'):
            return 'Numeric'
        if name == '_pg_expandarray':
            return 'ArrayFuncs'
        return 'Unsupported'
    if p['prolang'] != '12':
        return 'Unsupported'
    if src in io_syms or re.search(r'typmod(in|out)$', src):
        return 'Unsupported'  # type I/O is reached through crate::io, not the function registry
    if re.search(r'(sel|joinsel|support|sortsupport|skipsupport|typanalyze|_handler|consistent|penalty|picksplit|'
                 r'compress|_lexize|_init|_options|_union|_same|subdiff|_accum|_accum_inv|_combine|_serialize|'
                 r'_deserialize|_finalfn|_transfn|_final|_avg|_sum)$', src):
        return 'Unsupported'
    # aggregate transition/final helpers: aggregates are implemented natively in crate::agg
    if re.match(r'^(bool_alltrue|bool_anytrue|float8_(corr|covar_\w+|regr_\w+|stddev_\w+|var_\w+)|numeric_poly_\w+|'
                r'numeric_(stddev|var)_\w+|int8inc\w*|int8dec\w*|numeric_inc|enum_(in|out|recv|send))$', src):
        return 'Unsupported'
    if re.match(r'^(gin|gist|spg|brin|bt\w*equalimage|binary_upgrade|pg_stat_|be_lo|lo_|ts_|gts|tsvector|tsquery|'
                r'xml|pg_replication|pg_wal|pg_create_|pg_drop_|pg_copy_|pg_ls_|pg_read_|pg_logical|pg_backup|'
                r'pg_promote|pg_reload|pg_rotate|pg_log_|pg_control|pg_hba|pg_ident|pg_get_wal|pg_stat|pg_restore|'
                r'pg_clear|fmgr_|plpgsql|RI_FKey|unique_key_recheck|suppress_redundant|satisfies_hash|amvalidate|'
                r'pg_extension|pg_import|pg_event_trigger|pg_isolation|pg_safe_snapshot|pg_numa|pg_get_aios|'
                r'pg_get_shmem|pg_get_backend_memory|pg_get_loaded|pg_get_wait|pg_split_walfile|pg_tablespace|'
                r'pg_filenode|pg_nextoid|pg_relation_filepath|pg_current_logfile|pg_show_|pg_sync|pg_stop_|'
                r'pg_mcv|pg_ndistinct|pg_dependencies|pg_snapshot|pg_lsn|pg_visible_in_snapshot|'
                r'pg_xact_commit|pg_get_multixact|mxid_age|xid_age|pg_last_|pg_is_wal|pg_get_publication|'
                r'postgresql_fdw|pg_get_replica|pg_get_catalog_foreign_keys|pg_get_sequence_data|gen_random_uuid_x)',
                src):
        if not any(re.search(x, src) for x in EXTERNAL):
            return 'Unsupported'
    if any(re.search(x, src) for x in EXTERNAL):
        return 'External'
    if any(re.search(x, src) for x in SYSTEM):
        return 'System'
    for mod, rx in RULES:
        if re.match(rx, src):
            return mod
    return 'Unsupported'


