#!/usr/bin/env python3
"""Generate pgarbor-catalog builtin tables from the pinned PG 18.6 reference dumps.

Reproduce (from the repository root):

    python3 crates/pgarbor-catalog/gen/gen_builtin.py

Inputs (checked in, never hand-edited):
  contracts/reference/pg18/catalog_relations.csv     every pg_catalog / information_schema relation
  contracts/reference/pg18/catalog_attributes.csv    their columns (attnum > 0), exact names/types/typmods
  contracts/reference/pg18/pg_description_builtin.csv
  crates/pgarbor-catalog/gen/ref/*.csv               full rows of small builtin catalogs, dumped with
      podman exec -i pgarbor-oracle psql -U postgres -X -q -c \
        "COPY (select * from <catalog> order by oid) TO STDOUT WITH (FORMAT csv, HEADER true)"
      (pg_authid with rolpassword forced to NULL; pg_range ordered by rngtypid;
       pg_temp_N / pg_toast_temp_N namespaces removed from pg_namespace.csv)

Outputs (GENERATED, do not edit by hand; rerun this script instead):
  crates/pgarbor-catalog/src/builtin/system_rels.rs
  crates/pgarbor-catalog/src/builtin/objects.rs
  crates/pgarbor-catalog/src/builtin/descriptions.rs
"""
import csv
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
REF = os.path.join(ROOT, "contracts", "reference", "pg18")
LOCAL = os.path.join(ROOT, "crates", "pgarbor-catalog", "gen", "ref")
OUT = os.path.join(ROOT, "crates", "pgarbor-catalog", "src", "builtin")

NS = {"pg_catalog": 11, "information_schema": 13293, "pg_toast": 99, "public": 2200}
HEADER = "// @generated by crates/pgarbor-catalog/gen/gen_builtin.py from contracts/reference/pg18 (PostgreSQL 18.6).\n// DO NOT EDIT BY HAND.\n"


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + '"'


def opt_str(s):
    return "None" if s is None or s == "" else "Some(" + rs_str(s) + ")"


def b(s):
    return "true" if s == "t" else "false"


def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def const_name(nsp, rel):
    base = rel.upper()
    if nsp == "information_schema":
        base = "IS_" + base.lstrip("_")
        if rel.startswith("_"):
            base = "IS_PRIV_" + rel.lstrip("_").upper()
    return base


def gen_system_rels():
    rels = read(os.path.join(REF, "catalog_relations.csv"))
    attrs = read(os.path.join(REF, "catalog_attributes.csv"))
    cols = {}
    for a in attrs:
        cols.setdefault((a["nspname"], a["relname"]), []).append(a)
    rels.sort(key=lambda r: int(r["oid"]))
    out = [HEADER, "//! Every pg_catalog / information_schema relation of PG 18.6 (tables, views and indexes) with its\n",
           "//! exact column list. Sorted by OID. See `crate::builtin` for the struct docs.\n",
           "use super::{SysCol, SystemRel};\n\n"]
    out.append("/// Relation OID constants for every system table/view (`IS_*` = information_schema).\n")
    out.append("pub mod relid {\n    use pgarbor_common::Oid;\n")
    for r in rels:
        if r["relkind"] in ("r", "v"):
            out.append("    /// `%s.%s` (relkind '%s')\n" % (r["nspname"], r["relname"], r["relkind"]))
            out.append("    pub const %s: Oid = %s;\n" % (const_name(r["nspname"], r["relname"]), r["oid"]))
    out.append("}\n\n")
    out.append("/// All system relations, sorted by OID.\n")
    out.append("pub static SYSTEM_RELS: &[SystemRel] = &[\n")
    for r in rels:
        cl = cols.get((r["nspname"], r["relname"]), [])
        cl.sort(key=lambda a: int(a["attnum"]))
        if len(cl) != int(r["relnatts"]):
            sys.exit("column count mismatch for %s.%s" % (r["nspname"], r["relname"]))
        out.append("    SystemRel { oid: %s, name: %s, namespace: %d, kind: b'%s', rowtype: %s, columns: &[\n" % (
            r["oid"], rs_str(r["relname"]), NS[r["nspname"]], r["relkind"], r["reltype"]))
        for a in cl:
            out.append("        SysCol { attnum: %s, name: %s, type_oid: %s, typmod: %s, not_null: %s },\n" % (
                a["attnum"], rs_str(a["attname"]), a["atttypid"], a["atttypmod"], b(a["attnotnull"])))
        out.append("    ] },\n")
    out.append("];\n\n")
    out.append("/// Number of system relations.\npub const SYSTEM_REL_COUNT: usize = %d;\n\n" % len(rels))
    vdefs = read(os.path.join(REF, "catalog_view_defs.csv"))
    oid_of = {(r["nspname"], r["relname"]): int(r["oid"]) for r in rels}
    vl = sorted((oid_of[(v["schemaname"], v["viewname"])], v["definition"]) for v in vdefs)
    out.append("/// `pg_get_viewdef(oid)` text of every system view, sorted by view OID.\n")
    out.append("pub static SYSTEM_VIEW_DEFS: &[(u32, &str)] = &[\n")
    for o, d in vl:
        out.append("    (%d, %s),\n" % (o, rs_str(d)))
    out.append("];\n")
    with open(os.path.join(OUT, "system_rels.rs"), "w") as f:
        f.write("".join(out))


def gen_objects():
    L = lambda n: read(os.path.join(LOCAL, n + ".csv"))
    out = [HEADER, "//! Builtin rows of small shared/system catalogs (PG 18.6). See `crate::builtin` for struct docs.\n",
           "use super::{BuiltinAm, BuiltinCollation, BuiltinDatabase, BuiltinExtension, BuiltinLanguage, BuiltinNamespace,\n",
           "    BuiltinRole, BuiltinTablespace, TextRows};\n\n"]
    out.append("/// pg_namespace rows (pg_catalog, pg_toast, public, information_schema).\npub static NAMESPACES: &[BuiltinNamespace] = &[\n")
    for r in L("pg_namespace"):
        out.append("    BuiltinNamespace { oid: %s, name: %s, owner: %s, acl: %s },\n" % (r["oid"], rs_str(r["nspname"]), r["nspowner"], opt_str(r["nspacl"])))
    out.append("];\n\n/// pg_authid rows (bootstrap superuser `postgres` + predefined roles).\npub static ROLES: &[BuiltinRole] = &[\n")
    for r in L("pg_authid"):
        out.append("    BuiltinRole { oid: %s, name: %s, superuser: %s, inherit: %s, create_role: %s, create_db: %s, can_login: %s, replication: %s, bypass_rls: %s, conn_limit: %s },\n" % (
            r["oid"], rs_str(r["rolname"]), b(r["rolsuper"]), b(r["rolinherit"]), b(r["rolcreaterole"]), b(r["rolcreatedb"]),
            b(r["rolcanlogin"]), b(r["rolreplication"]), b(r["rolbypassrls"]), r["rolconnlimit"]))
    out.append("];\n\n/// pg_auth_members rows as text: oid, roleid, member, grantor, admin_option, inherit_option, set_option.\n")
    out.append("pub static AUTH_MEMBERS: TextRows = TextRows { rel: 1261, rows: &[\n")
    for r in L("pg_auth_members"):
        out.append("    &[%s],\n" % ", ".join(opt_str(r[k]) for k in ["oid", "roleid", "member", "grantor", "admin_option", "inherit_option", "set_option"]))
    out.append("] };\n\n/// pg_database rows (template1, template0, postgres).\npub static DATABASES: &[BuiltinDatabase] = &[\n")
    for r in L("pg_database"):
        out.append("    BuiltinDatabase { oid: %s, name: %s, owner: %s, encoding: %s, locale_provider: b'%s', is_template: %s, allow_conn: %s, has_login_event_trigger: %s, conn_limit: %s, frozen_xid: %s, min_mxid: %s, tablespace: %s, collate: %s, ctype: %s, locale: %s, icu_rules: %s, coll_version: %s, acl: %s },\n" % (
            r["oid"], rs_str(r["datname"]), r["datdba"], r["encoding"], r["datlocprovider"], b(r["datistemplate"]), b(r["datallowconn"]),
            b(r["dathasloginevt"]), r["datconnlimit"], r["datfrozenxid"], r["datminmxid"], r["dattablespace"], rs_str(r["datcollate"]),
            rs_str(r["datctype"]), opt_str(r["datlocale"]), opt_str(r["daticurules"]), opt_str(r["datcollversion"]), opt_str(r["datacl"])))
    out.append("];\n\n/// pg_collation rows, sorted by OID.\npub static COLLATIONS: &[BuiltinCollation] = &[\n")
    for r in L("pg_collation"):
        out.append("    BuiltinCollation { oid: %s, name: %s, namespace: %s, owner: %s, provider: b'%s', deterministic: %s, encoding: %s, collate: %s, ctype: %s, locale: %s, icu_rules: %s, version: %s },\n" % (
            r["oid"], rs_str(r["collname"]), r["collnamespace"], r["collowner"], r["collprovider"], b(r["collisdeterministic"]), r["collencoding"],
            opt_str(r["collcollate"]), opt_str(r["collctype"]), opt_str(r["colllocale"]), opt_str(r["collicurules"]), opt_str(r["collversion"])))
    out.append("];\n\n/// pg_am rows.\npub static ACCESS_METHODS: &[BuiltinAm] = &[\n")
    for r in L("pg_am"):
        out.append("    BuiltinAm { oid: %s, name: %s, handler: %s, amtype: b'%s' },\n" % (r["oid"], rs_str(r["amname"]), rs_str(r["amhandler"]), r["amtype"]))
    out.append("];\n\n/// pg_language rows.\npub static LANGUAGES: &[BuiltinLanguage] = &[\n")
    for r in L("pg_language"):
        out.append("    BuiltinLanguage { oid: %s, name: %s, owner: %s, is_pl: %s, trusted: %s, call_handler: %s, inline_handler: %s, validator: %s },\n" % (
            r["oid"], rs_str(r["lanname"]), r["lanowner"], b(r["lanispl"]), b(r["lanpltrusted"]), r["lanplcallfoid"], r["laninline"], r["lanvalidator"]))
    out.append("];\n\n/// pg_tablespace rows.\npub static TABLESPACES: &[BuiltinTablespace] = &[\n")
    for r in L("pg_tablespace"):
        out.append("    BuiltinTablespace { oid: %s, name: %s, owner: %s },\n" % (r["oid"], rs_str(r["spcname"]), r["spcowner"]))
    out.append("];\n\n/// pg_extension rows.\npub static EXTENSIONS: &[BuiltinExtension] = &[\n")
    for r in L("pg_extension"):
        out.append("    BuiltinExtension { oid: %s, name: %s, owner: %s, namespace: %s, relocatable: %s, version: %s },\n" % (
            r["oid"], rs_str(r["extname"]), r["extowner"], r["extnamespace"], b(r["extrelocatable"]), rs_str(r["extversion"])))
    out.append("];\n\n")
    for name, rel, keys in [
        ("OPCLASSES", 2616, ["oid", "opcmethod", "opcname", "opcnamespace", "opcowner", "opcfamily", "opcintype", "opcdefault", "opckeytype"]),
        ("OPFAMILIES", 2753, ["oid", "opfmethod", "opfname", "opfnamespace", "opfowner"]),
        ("RANGES", 3541, ["rngtypid", "rngsubtype", "rngmultitypid", "rngcollation", "rngsubopc", "rngcanonical", "rngsubdiff"]),
    ]:
        fname = {"OPCLASSES": "pg_opclass", "OPFAMILIES": "pg_opfamily", "RANGES": "pg_range"}[name]
        out.append("/// %s rows as PG text output, columns in catalog order: %s.\n" % (fname, ", ".join(keys)))
        out.append("pub static %s: TextRows = TextRows { rel: %d, rows: &[\n" % (name, rel))
        for r in L(fname):
            out.append("    &[%s],\n" % ", ".join(opt_str(r[k]) for k in keys))
        out.append("] };\n\n")
    with open(os.path.join(OUT, "objects.rs"), "w") as f:
        f.write("".join(out))


def gen_descriptions():
    cls = {"pg_proc": 1255, "pg_type": 1247, "pg_operator": 2617}
    rows = read(os.path.join(REF, "pg_description_builtin.csv"))
    rows = [(cls[r["classname"]], int(r["objoid"]), r["description"]) for r in rows]
    rows.sort()
    out = [HEADER, "//! Builtin pg_description rows (objsubid 0) for procs, types and operators, sorted by (classoid, objoid).\n\n",
           "/// (classoid, objoid, description).\npub static BUILTIN_DESCRIPTIONS: &[(u32, u32, &str)] = &[\n"]
    for c, o, d in rows:
        out.append("    (%d, %d, %s),\n" % (c, o, rs_str(d)))
    out.append("];\n")
    with open(os.path.join(OUT, "descriptions.rs"), "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    gen_system_rels()
    gen_objects()
    gen_descriptions()
    print("generated system_rels.rs, objects.rs, descriptions.rs")
