#!/usr/bin/env python3
"""Generate crates/pgarbor/src/guc_table.rs from gen/pg_settings_full.csv.

pg_settings_full.csv was dumped from the pinned PG18.6 oracle with:
  podman exec -i pgarbor-oracle psql -U postgres -X -c "\\copy (select name, setting, unit, category,
    short_desc, extra_desc, context, vartype, source, min_val, max_val, enumvals, boot_val, reset_val
    from pg_settings order by name) to stdout csv header"
Run:  python3 crates/pgarbor/gen/gen_guc.py   (from the repository root)
"""
import csv, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, "pg_settings_full.csv"), newline="")))

# GUC_REPORT parameters of PG 18 (guc_parameters.dat flags REPORT).
REPORT = {
    "application_name", "client_encoding", "DateStyle", "default_transaction_read_only", "in_hot_standby",
    "integer_datetimes", "IntervalStyle", "is_superuser", "scram_iterations", "search_path", "server_encoding",
    "server_version", "session_authorization", "standard_conforming_strings", "TimeZone",
}

# PGArbor default overrides (SHOW form): name -> value
OVERRIDE = {
    "server_version": "18.6",
    "application_name": "",
    "client_encoding": "UTF8",
    "TimeZone": "UTC",
    "server_encoding": "UTF8",
    "data_directory": "",
    "config_file": "",
    "hba_file": "",
    "ident_file": "",
    "lc_messages": "C.UTF-8",
    "lc_monetary": "C.UTF-8",
    "lc_numeric": "C.UTF-8",
    "lc_time": "C.UTF-8",
    "default_text_search_config": "pg_catalog.simple",
    "log_timezone": "UTC",
    "transaction_isolation": "read committed",
    "session_authorization": "postgres",
    "is_superuser": "on",
    "unix_socket_directories": "",
    "listen_addresses": "localhost",
    "port": "5432",
}

CTX = {"internal": "Internal", "postmaster": "Postmaster", "sighup": "Sighup", "superuser-backend": "SuperuserBackend",
       "backend": "Backend", "superuser": "Superuser", "user": "User"}
TYP = {"bool": "Bool", "integer": "Int", "real": "Real", "string": "String", "enum": "Enum"}


def rs(s):
    return json.dumps(s, ensure_ascii=False)


def parse_enum(s):
    s = s.strip()
    if not s:
        return []
    assert s[0] == "{" and s[-1] == "}", s
    return next(csv.reader([s[1:-1]], skipinitialspace=False))


out = []
out.append("//! GENERATED by gen/gen_guc.py from the PG 18.6 oracle (`pg_settings`). DO NOT EDIT BY HAND.\n")
out.append("use crate::guc_def::{GucContext, GucDef, GucType};\n\n")
out.append("pub static GUC_DEFS: &[GucDef] = &[\n")
for r in rows:
    name = r["name"]
    boot = OVERRIDE.get(name, r["reset_val"])
    ev = parse_enum(r["enumvals"])
    out.append("    GucDef {\n")
    out.append(f"        name: {rs(name)},\n")
    out.append(f"        category: {rs(r['category'])},\n")
    out.append(f"        short_desc: {rs(r['short_desc'])},\n")
    out.append(f"        extra_desc: {rs(r['extra_desc'])},\n")
    out.append(f"        context: GucContext::{CTX[r['context']]},\n")
    out.append(f"        vartype: GucType::{TYP[r['vartype']]},\n")
    out.append(f"        unit: {rs(r['unit'])},\n")
    out.append(f"        min_val: {rs(r['min_val'])},\n")
    out.append(f"        max_val: {rs(r['max_val'])},\n")
    out.append("        enumvals: &[" + ", ".join(rs(e) for e in ev) + "],\n")
    out.append(f"        boot_val: {rs(boot)},\n")
    out.append(f"        report: {'true' if name in REPORT else 'false'},\n")
    out.append("    },\n")
out.append("];\n")
open(os.path.join(HERE, "..", "src", "guc_table.rs"), "w").write("".join(out))
print("wrote", len(rows), "definitions")
